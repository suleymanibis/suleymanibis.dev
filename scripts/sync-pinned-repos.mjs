import { mkdir, writeFile } from "node:fs/promises";

const token = process.env.GITHUB_TOKEN;
const username = process.env.GITHUB_USERNAME || "suleymanibis";

if (!token) {
  throw new Error("GITHUB_TOKEN is required. Use the GitHub Actions secret or set it locally.");
}

const query = `query($login: String!) {
  user(login: $login) {
    pinnedItems(first: 6, types: REPOSITORY) {
      nodes {
        ... on Repository {
          name
          description
          url
          primaryLanguage { name }
        }
      }
    }
  }
}`;

const response = await fetch("https://api.github.com/graphql", {
  method: "POST",
  headers: {
    Accept: "application/vnd.github+json",
    Authorization: `Bearer ${token}`,
    "Content-Type": "application/json",
    "User-Agent": "suleymanibis-portfolio-pinned-sync"
  },
  body: JSON.stringify({ query, variables: { login: username } })
});

if (!response.ok) {
  throw new Error(`GitHub GraphQL request failed with HTTP ${response.status}.`);
}

const payload = await response.json();
if (payload.errors?.length) {
  throw new Error(`GitHub GraphQL error: ${payload.errors.map((error) => error.message).join("; ")}`);
}

const nodes = payload.data?.user?.pinnedItems?.nodes;
if (!Array.isArray(nodes) || nodes.length === 0) {
  throw new Error(`No pinned repositories returned for GitHub user "${username}".`);
}

const projects = nodes.map((repo) => ({
  repo: repo.name,
  summary: repo.description || "",
  language: repo.primaryLanguage?.name || "",
  url: repo.url
}));

await mkdir("generated", { recursive: true });
await writeFile(
  "generated/pinned-projects.js",
  `// Generated by scripts/sync-pinned-repos.mjs. Do not edit manually.\nexport const pinnedProjects = ${JSON.stringify(projects, null, 2)};\n`,
  "utf8"
);
console.log(`Synced ${projects.length} pinned repositories for ${username}.`);
